"""Tiered context loading (OpenViking adoption).

Every context file gets three load levels so an agent checks relevance
before paying for full content:

- **L0 ``.abstract.md``** — generated one-paragraph summary (name +
  description + triggers). ``find``/relevance checks read only this.
- **L1 overview** — frontmatter + first section, enough for planning.
- **L2 full** — the original file, read only when actually needed.

L0 files are generated artifacts: ``aizee abstract`` regenerates them;
they carry a ``<!-- generated -->`` marker and are never hand-edited.
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from pathlib import Path

import yaml

GENERATED_MARKER = "<!-- generated by aizee abstract — do not edit -->"
_L1_MAX_LINES = 50
_TIERED_DIRS = ("skills", "tech-stack", "workflows")
_ABSTRACT_MAX = 400
_SKIP_FILES = {"index.json", "README.md"}


@dataclass(frozen=True)
class AbstractResult:
    """Outcome of one abstract generation."""

    source: str
    abstract_path: str
    written: bool


def _frontmatter(text: str) -> dict[str, object]:
    if not text.startswith("---"):
        return {}
    end = text.find("\n---", 3)
    if end < 0:
        return {}
    data = yaml.safe_load(text[3:end])
    return data if isinstance(data, dict) else {}


def _first_paragraph(body: str) -> str:
    for block in re.split(r"\n\s*\n", body):
        block = block.strip()
        if block and not block.startswith(("#", "---", "<!--")):
            return " ".join(block.split())
    return ""


def generate_abstract(path: Path, text: str) -> str:
    """Build the L0 abstract for one context file."""
    meta = _frontmatter(text)
    name = str(meta.get("name") or path.stem)
    desc = str(meta.get("description") or "").strip()
    triggers = meta.get("triggers")
    if isinstance(triggers, str):
        triggers = [triggers]
    trigger_line = ""
    if isinstance(triggers, list) and triggers:
        shown = ", ".join(str(t) for t in triggers[:8])
        trigger_line = f"\nUse when: {shown}"
    if not desc:
        body = text.split("---", 2)[-1] if text.startswith("---") else text
        desc = _first_paragraph(body)
    abstract = f"{GENERATED_MARKER}\n# {name}\n{desc}{trigger_line}\n"
    if len(abstract) > _ABSTRACT_MAX:
        abstract = abstract[: _ABSTRACT_MAX - 2].rstrip() + "…\n"
    return abstract


def abstract_path_for(source: Path, root: Path) -> Path:
    """Where the L0 file lives: a mirror tree under ``abstracts/``.

    Sidecars intentionally live OUTSIDE skills/tech-stack/workflows —
    every scanner that globs ``*.md`` there (catalog, ingest, lint) must
    not see generated summaries as broken skills.
    """
    rel = source.relative_to(root)
    return root / "abstracts" / rel


def write_abstract(source: Path, root: Path, force: bool = False) -> AbstractResult:
    rel = str(source.relative_to(root)).replace("\\", "/")
    target = abstract_path_for(source, root)
    if target.exists() and not force:
        return AbstractResult(source=rel, abstract_path=str(target.relative_to(root)), written=False)
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(
        generate_abstract(source, source.read_text(encoding="utf-8")),
        encoding="utf-8",
    )
    return AbstractResult(
        source=rel,
        abstract_path=str(target.relative_to(root)).replace("\\", "/"),
        written=True,
    )


def generate_all(
    root: Path, dirs: tuple[str, ...] = _TIERED_DIRS, force: bool = False
) -> dict[str, object]:
    """(Re)generate L0 abstracts across the tiered directories."""
    results: list[AbstractResult] = []
    for dirname in dirs:
        base = root / dirname
        if not base.is_dir():
            continue
        for path in sorted(base.rglob("*.md")):
            if path.name in _SKIP_FILES or "abstracts" in path.parts:
                continue
            results.append(write_abstract(path, root, force=force))
    written = [r for r in results if r.written]
    return {
        "ok": True,
        "scanned": len(results),
        "written": len(written),
        "files": [r.abstract_path for r in written],
    }


def read_context(path: Path, level: str = "l1", root: Path | None = None) -> str:
    """Read a context file at the requested tier.

    ``l0`` → mirror abstract under ``abstracts/`` (falls back to overview
    when missing); ``l1`` → frontmatter + first section (~50 lines);
    ``l2`` → full text.
    """
    text = path.read_text(encoding="utf-8")
    if level == "l2":
        return text
    if level == "l0":
        base = root or path.parent
        try:
            abstract = abstract_path_for(path, base)
        except ValueError:
            abstract = Path("__nonexistent__")
        if abstract.exists():
            return abstract.read_text(encoding="utf-8")
        return _overview(text, abstract_fallback=True)
    return _overview(text)


def _overview(text: str, abstract_fallback: bool = False) -> str:
    lines = text.splitlines()
    if abstract_fallback:
        return "\n".join(lines[:20])
    # L1: frontmatter + content up to the second `## ` heading, capped.
    cut = len(lines)
    headings = [i for i, line in enumerate(lines) if line.startswith("## ")]
    if len(headings) > 1:
        cut = min(cut, headings[1])
    return "\n".join(lines[: min(cut, _L1_MAX_LINES)])
